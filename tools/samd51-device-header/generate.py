def num(text):
    return int(text, 0)


def camel(name):
    return ''.join(part[:1].upper() + part[1:].lower() for part in name.split('_'))


def width_type(size):
    return {1: 'uint8_t', 2: 'uint16_t', 4: 'uint32_t'}[size]


def reserved_type(size):
    return {1: 'RoReg8', 2: 'RoReg16', 4: 'RoReg'}[size]


def qualifier(register):
    rw = register.get('rw', 'RW')
    return {'R': '__I ', 'W': '__O ', 'RW': '__IO'}[rw]


def mask_runs(mask):
    runs, bit = [], 0
    while mask >> bit:
        if mask >> bit & 1:
            start = bit
            while mask >> bit & 1:
                bit += 1
            runs.append((start, bit - start))
        else:
            bit += 1
    return runs


class Generator:
    def __init__(self, root):
        self.root = root
        self.modules = {m.get('name'): m for m in root.find('modules')}
        self.device = root.find('devices/device')
        self.values = {}
        for module in self.modules.values():
            for group in module.findall('value-group'):
                self.values[(module.get('name'), group.get('name'))] = group

    def mode_name(self, module, mode):
        return MODE_NAMES.get((module, mode), mode)

    def register_prefix(self, module, register, mode):
        if mode:
            return f'{module}_{self.mode_name(module, mode)}_{register.get("name")}'
        return f'{module}_{register.get("name")}'

    @staticmethod
    def submodes(register):
        """Register-level bitfield views: DEFAULT is `bit`, others are named members."""
        names = [m.get('name') for m in register.findall('mode')]
        return names or ['DEFAULT']

    def bitfields(self, module, register, submode='DEFAULT'):
        fields = []
        for field in register.findall('bitfield'):
            modes = field.get('modes')
            if modes and submode not in modes.split():
                continue
            runs = mask_runs(num(field.get('mask')))
            if len(runs) != 1:
                raise ValueError(f'{module}.{register.get("name")}.{field.get("name")}: noncontiguous mask')
            fields.append((runs[0][0], runs[0][1], field))
        return sorted(fields, key=lambda f: f[0])

    def register_type(self, out, module, register, mode, emitted):
        prefix = self.register_prefix(module, register, mode)
        if prefix in emitted:
            return prefix + '_Type'
        emitted.add(prefix)
        size = num(register.get('size'))
        bits = size * 8
        ctype = width_type(size)
        views = [(s, self.bitfields(module, register, s)) for s in self.submodes(register)]
        fields = dict(views).get('DEFAULT', views[0][1])
        out.append(f'/* -------- {prefix} : ({register.get("rw", "RW")} {bits}) {register.get("caption", "")} -------- */')
        out.append('#if !(defined(__ASSEMBLY__) || defined(__IAR_SYSTEMS_ASM__))')
        out.append('typedef union {')
        for submode, view in views:
            if not view:
                continue
            out.append('  struct {')
            at = 0
            for position, width, field in view:
                if position > at:
                    out.append(f'    {ctype} :{position - at};')
                if submode == 'DEFAULT' and self.one_hot(module, field, width):
                    out += [f'    {ctype} {field.get("name")}{k}:1;' for k in range(width)]
                else:
                    out.append(f'    {ctype} {field.get("name")}:{width};')
                at = position + width
            if at < bits:
                out.append(f'    {ctype} :{bits - at};')
            out.append('  } ' + ('bit' if submode == 'DEFAULT' else submode) + ';')
        if fields:
            groups = self.numbered_groups(fields) + [(f.get('name'), p, w) for p, w, f in fields if self.one_hot(module, f, w)]
            groups.sort(key=lambda g: g[1])
            if groups:
                out.append('  struct {')
                at = 0
                for name, position, count in groups:
                    if position > at:
                        out.append(f'    {ctype} :{position - at};')
                    out.append(f'    {ctype} {name}:{count};')
                    at = position + count
                if at < bits:
                    out.append(f'    {ctype} :{bits - at};')
                out.append('  } vec;')
        out.append(f'  {ctype} reg;')
        out.append(f'}} {prefix}_Type;')
        out.append('#endif /* !(defined(__ASSEMBLY__) || defined(__IAR_SYSTEMS_ASM__)) */')
        out.append('')
        out.append(f'#define {prefix}_OFFSET {"_U_(" + register.get("offset") + ")"}')
        if register.get('initval'):
            out.append(f'#define {prefix}_RESETVALUE _U_({register.get("initval")})')
        total = 0
        for submode, view in views:
            if submode != 'DEFAULT':
                total |= self.field_macros(out, module, f'{prefix}_{submode}', view)
        total |= self.field_macros(out, module, prefix, fields)
        for name, position, count in self.numbered_groups(fields):
            full = f'{prefix}_{name}'
            out.append(f'#define {full}_Pos {position}')
            out.append(f'#define {full}_Msk (_U_({(1 << count) - 1:#x}) << {full}_Pos)')
            out.append(f'#define {full}(value) ({full}_Msk & ((value) << {full}_Pos))')
        out.append(f'#define {prefix}_MASK _U_({total:#x})')
        out.append('')
        return prefix + '_Type'

    def field_macros(self, out, module, prefix, fields):
        total = 0
        for position, width, field in fields:
            # A trailing underscore keeps a bitfield distinct from an instance
            # macro (MCLK .bit.TC0_); its mask macro drops it (MCLK_APBAMASK_TC0).
            name = f'{prefix}_{field.get("name").rstrip("_")}'
            mask = (1 << width) - 1
            total |= mask << position
            out.append(f'#define {name}_Pos {position}')
            if width == 1:
                out.append(f'#define {name} (_U_(0x1) << {name}_Pos)')
            else:
                out.append(f'#define {name}_Msk (_U_({mask:#x}) << {name}_Pos)')
                out.append(f'#define {name}(value) ({name}_Msk & ((value) << {name}_Pos))')
            if self.one_hot(module, field, width):
                out += [f'#define {name}{k} (_U_(0x1) << ({name}_Pos + {k}))' for k in range(width)]
            group = field.get('values')
            if group and (module, group) in self.values:
                for value in self.values[(module, group)].findall('value'):
                    vname = f'{name}_{value.get("name")}'
                    out.append(f'#define   {vname}_Val _U_({num(value.get("value")):#x})')
                    out.append(f'#define {vname} ({vname}_Val << {name}_Pos)')
        return total

    def one_hot(self, module, field, width):
        """A field whose value group is exactly one bit per position (SYNCBUSY.GENCTRL)."""
        group = field.get('values')
        if width < 2 or not group or (module, group) not in self.values:
            return False
        values = sorted(num(v.get('value')) for v in self.values[(module, group)].findall('value'))
        return values == [1 << k for k in range(width)]

    @staticmethod
    def numbered_groups(fields):
        """Legacy vector fields: MC0, MC1 -> MC (contiguous one-bit siblings)."""
        found = {}
        for position, width, field in fields:
            match = re.fullmatch(r'([A-Z_]*[A-Z_])(\d+)', field.get('name'))
            if match and width == 1:
                found.setdefault(match.group(1), []).append((int(match.group(2)), position))
        names = {f.get('name') for _, _, f in fields}
        groups = []
        for stem, members in found.items():
            members.sort()
            if len(members) < 2 or stem in names or stem == 'MASK':
                continue
            indexes = [i for i, _ in members]
            positions = [p for _, p in members]
            if indexes != list(range(indexes[0], indexes[0] + len(indexes))):
                continue
            if positions != list(range(positions[0], positions[0] + len(positions))):
                continue
            groups.append((stem, positions[0], len(positions)))
        return sorted(groups, key=lambda g: g[1])

    def group_members(self, module, group, mode):
        """Registers and nested groups visible in one mode of a register group."""
        members = []
        for item in group:
            if item.tag not in ('register', 'register-group'):
                continue
            modes = item.get('modes')
            if modes and mode not in modes.split():
                continue
            if not modes and mode is None and any(x.tag == 'mode' for x in group):
                continue
            members.append(item)
        return members

    def struct(self, out, module, group, mode, name, emitted, structs):
        members = self.group_members(module, group, mode)
        fields = []
        for item in members:
            offset = num(item.get('offset'))
            count = num(item.get('count')) if item.get('count') else None
            if item.tag == 'register':
                ctype = self.register_type(out, module, item, mode if item.get('modes') else None, emitted)
                size = num(item.get('size'))
                member = item.get('name')
                fields.append((offset, size * (count or 1), f'  {qualifier(item)} {ctype} {member}' + (f'[{count}]' if count else '') + ';'))
            else:
                sub = self.subgroup(module, item.get('name-in-module'))
                subname = camel(module) + camel(item.get('name-in-module'))
                if subname not in structs:
                    self.struct(out, module, sub, mode if sub.find('mode') is not None else None, subname, emitted, structs)
                size = num(sub.get('size'))
                member = camel(item.get('name'))
                fields.append((offset, size * (count or 1), f'       {subname} {member}' + (f'[{count}]' if count else '') + ';'))
        fields.sort(key=lambda f: f[0])
        lines, at, pad = [], 0, 0
        for offset, size, text in fields:
            if offset < at:
                raise ValueError(f'{name}: overlapping member at {offset:#x}')
            if offset > at:
                pad += 1
                lines.append(f'       RoReg8 Reserved{pad}[{offset - at:#x}];')
            lines.append(text)
            at = offset + size
        if group.get('size'):
            end = num(group.get('size'))
            if end > at:
                pad += 1
                lines.append(f'       RoReg8 Reserved{pad}[{end - at:#x}];')
        out.append('#if !(defined(__ASSEMBLY__) || defined(__IAR_SYSTEMS_ASM__))')
        out.append('typedef struct {')
        out.extend(lines)
        out.append(f'}} {name};')
        out.append('#endif /* !(defined(__ASSEMBLY__) || defined(__IAR_SYSTEMS_ASM__)) */')
        out.append('')
        structs.add(name)

    def subgroup(self, module, name):
        for group in self.modules[module].findall('register-group'):
            if group.get('name') == name:
                return group
        raise ValueError(f'{module}: no register group {name}')

    def component(self, module):
        node = self.modules[module]
        out = [f'#ifndef _SAMD51_{module}_COMPONENT_', f'#define _SAMD51_{module}_COMPONENT_', '']
        emitted, structs = set(), set()
        top = [g for g in node.findall('register-group') if g.get('name') == module]
        others = [g for g in node.findall('register-group') if g.get('name') != module]
        for group in top:
            modes = [m.get('name') for m in group.findall('mode') if (module, m.get('name')) not in DROPPED_MODES]
            if modes:
                for mode in modes:
                    self.struct(out, module, group, mode, camel(module) + camel(self.mode_name(module, mode)), emitted, structs)
                out.append('#if !(defined(__ASSEMBLY__) || defined(__IAR_SYSTEMS_ASM__))')
                out.append('typedef union {')
                for mode in modes:
                    out.append(f'       {camel(module) + camel(self.mode_name(module, mode))} {self.mode_name(module, mode)};')
                out.append(f'}} {camel(module)};')
                out.append('#endif')
                out.append('')
            else:
                self.struct(out, module, group, None, camel(module), emitted, structs)
        # Memory-resident descriptor layouts (DMAC_DESCRIPTOR) and unreferenced groups.
        for group in others:
            suffix = camel(group.get('name').replace(module + '_', '', 1))
            modes = [m.get('name') for m in group.findall('mode')]
            if modes and any(g.tag == 'register-group' for g in group):
                for mode in modes:
                    self.struct(out, module, group, mode, camel(module) + camel(mode) + suffix, emitted, structs)
                out += ['#if !(defined(__ASSEMBLY__) || defined(__IAR_SYSTEMS_ASM__))', 'typedef union {']
                out += [f'       {camel(module) + camel(mode) + suffix} {mode};' for mode in modes]
                out += [f'}} {camel(module) + suffix};', '#endif', '']
                continue
            name = camel(module) + suffix
            if module == 'DMAC' and group.get('name') == 'DMAC_DESCRIPTOR':
                name = 'DmacDescriptor'
            if name not in structs and not group.findall('mode'):
                self.struct(out, module, group, None, name, emitted, structs)
        out.append(f'#endif /* _SAMD51_{module}_COMPONENT_ */')
        return out

    def interrupts(self):
        lines = []
        rows = [(num(i.get('index')), i.get('name'), i.get('module-instance'), i.get('caption', ''))
                for i in self.device.find('interrupts')]
        per = {}
        for index, name, instance, _ in rows:
            if index >= 0:
                per.setdefault(instance or name, []).append(index)
        names = {}
        for index, name, instance, caption in rows:
            if index < 0:
                if name != 'Reset':
                    names[index] = [f'{name}_IRQn']
                continue
            owner = instance or name
            legacy = owner if len(per[owner]) == 1 else f'{owner}_{per[owner].index(index)}'
            names[index] = [f'{legacy}_IRQn'] + ([f'{name}_IRQn'] if name != legacy else [])
        seen = set()
        lines.append('typedef enum IRQn {')
        for index in sorted(names):
            for spelling in names[index]:
                if spelling in seen:
                    continue
                seen.add(spelling)
                lines.append(f'  {spelling} = {index},')
        lines.append(f'  PERIPH_COUNT_IRQn = {max(names) + 1}')
        lines.append('} IRQn_Type;')
        return lines

    def vectors(self):
        """Legacy DeviceVectors table and handler prototypes, in exception order."""
        rows = [(num(i.get('index')), i.get('name'), i.get('module-instance')) for i in self.device.find('interrupts')]
        per = {}
        for index, name, instance in rows:
            if index >= 0:
                per.setdefault(instance or name, []).append(index)
        legacy = {}
        for index, name, instance in rows:
            if index >= 0:
                owner = instance or name
                legacy[index] = owner if len(per[owner]) == 1 else f'{owner}_{per[owner].index(index)}'
        core = {-15: 'Reset', -14: 'NMI', -13: 'HardFault', -12: 'MemManage', -11: 'BusFault',
                -10: 'UsageFault', -5: 'SVC', -4: 'DebugMon', -2: 'PendSV', -1: 'SysTick'}
        lines = ['#if !(defined(__ASSEMBLY__) || defined(__IAR_SYSTEMS_ASM__))', 'typedef struct _DeviceVectors {',
                 '  void* pvStack;']
        for index in range(-15, 0):
            lines.append(f'  void* pfn{core[index]}_Handler;' if index in core else f'  void* pvReservedM{-index};')
        count = num({p.get('name'): p.get('value') for p in self.device.find('parameters')}['NUM_IRQ'])
        for index in range(count):
            lines.append(f'  void* pfn{legacy[index]}_Handler;' if index in legacy else f'  void* pvReserved{index};')
        lines += ['} DeviceVectors;', '']
        names = [core[i] for i in sorted(core)] + [legacy[i] for i in sorted(legacy)]
        lines += [f'void {name}_Handler(void);' for name in names]
        lines += ['#endif', '']
        self.vector_names = (core, legacy, count)
        return lines

    def vector_table(self):
        """The exception table: every named vector a weak alias of Dummy_Handler."""
        core, legacy, count = self.vector_names
        names = [core[i] for i in sorted(core) if i != -15] + [legacy[i] for i in sorted(legacy)]
        lines = [f'#include "{DEVICE.lower()}.h"', '', 'extern uint32_t _estack;', '',
                 '// An unexpected exception or interrupt stops here.',
                 'void Dummy_Handler(void)', '{', '    for (;;) {', '    }', '}', '']
        lines += [f'void {n}_Handler(void) __attribute__((weak, alias("Dummy_Handler")));' for n in names]
        lines += ['', '__attribute__((section(".vectors"), used)) const DeviceVectors exception_table = {',
                  '    .pvStack = (void *)(&_estack),', '    .pfnReset_Handler = (void *)Reset_Handler,']
        lines += [f'    .pfn{n}_Handler = (void *){n}_Handler,' for n in names]
        lines += ['};']
        return lines

    def instances(self):
        lines, peripherals = [], self.device.find('peripherals')
        for peripheral in peripherals:
            module = peripheral.get('name')
            if module in SKIPPED_MODULES:
                continue
            ctype = camel(module)
            names = []
            for instance in peripheral.findall('instance'):
                name = instance.get('name')
                names.append(name)
                group = instance.find('register-group')
                if group is not None and module in self.modules:
                    lines.append(f'#define {name} (({ctype} *){num(group.get("offset")):#010x}UL)')
                for param in instance.findall('parameters/param'):
                    value = param.get('value')
                    if re.fullmatch(r'-?(0x[0-9A-Fa-f]+|\d+)', value or ''):
                        lines.append(f'#define {name}_{param.get("name")} {value}')
                        if param.get('name') == 'INSTANCE_ID':
                            lines.append(f'#define ID_{name} {value}')
            lines.append(f'#define {module}_INST_NUM {len(names)}')
            lines.append(f'#define {module}_INSTS {{ {", ".join(names)} }}')
            lines.append('')
        return lines

    def pins(self):
        lines, seen = [], set()
        pads = set()
        for peripheral in self.device.find('peripherals'):
            for instance in peripheral.findall('instance'):
                for signal in instance.findall('signals/signal'):
                    pad, function = signal.get('pad'), signal.get('function')
                    if not pad or not re.fullmatch(r'P[A-D]\d\d', pad) or not re.fullmatch(r'[A-N]', function or ''):
                        continue
                    pads.add(pad)
                    pin = (ord(pad[1]) - ord('A')) * 32 + int(pad[2:])
                    group = signal.get('group') + (signal.get('index') or '')
                    label = f'{pad}{function}_{instance.get("name")}_{group}'
                    if label in seen:
                        continue
                    seen.add(label)
                    mux = ord(function) - ord('A')
                    lines += [f'#define PIN_{label} _L_({pin})', f'#define MUX_{label} _L_({mux})',
                              f'#define PINMUX_{label} ((PIN_{label} << 16) | MUX_{label})',
                              f'#define PORT_{label} (_UL_(1) << {pin % 32})']
        head = []
        for pad in sorted(pads):
            pin = (ord(pad[1]) - ord('A')) * 32 + int(pad[2:])
            head += [f'#define PIN_{pad} {pin}', f'#define PORT_{pad} (_UL_(1) << {pin % 32})']
        return head + lines

    def pin_table(self):
        """Per-pad peripheral functions for the selected drivers' pin objects."""
        pads = {}
        def entry(pad):
            return pads.setdefault(pad, dict(extint=None, adc=[None, None], timer=[None, None, None], sercom=[None, None]))
        for peripheral in self.device.find('peripherals'):
            module = peripheral.get('name')
            for instance in peripheral.findall('instance'):
                name = instance.get('name')
                for signal in instance.findall('signals/signal'):
                    pad, function, group, index = signal.get('pad'), signal.get('function'), signal.get('group'), signal.get('index')
                    if not pad or not re.fullmatch(r'P[A-D]\d\d', pad) or index is None:
                        continue
                    row, index = entry(pad), int(index)
                    if module == 'EIC' and group == 'EXTINT' and function == 'A':
                        row['extint'] = index
                    elif module == 'ADC' and group == 'AIN' and function == 'B':
                        row['adc'][int(name[-1])] = index
                    elif module == 'TC' and group == 'WO' and function == 'E':
                        row['timer'][0] = (int(name[2:]), 1, index)
                    elif module == 'TCC' and group == 'WO' and function in 'FG':
                        row['timer'][1 if function == 'F' else 2] = (int(name[3:]), 0, index)
                    elif module == 'SERCOM' and group == 'PAD' and function in 'CD':
                        row['sercom'][0 if function == 'C' else 1] = (int(name[6:]), index)
        lines = ['#include "samd/pins.h"', '', 'const mcu_pin_obj_t samd_pins[] = {']
        for pad in sorted(pads, key=lambda p: (p[1], int(p[2:]))):
            row = pads[pad]
            number = (ord(pad[1]) - ord('A')) * 32 + int(pad[2:])
            extint = '1, %d' % row['extint'] if row['extint'] is not None else '0, 0'
            adc = ', '.join('NO_ADC' if a is None else str(a) for a in row['adc'])
            timers = ', '.join('{0x3f, 0, 0}' if t is None else '{%d, %d, %d}' % t for t in row['timer'])
            sercoms = ', '.join('{0x3f, 0}' if s is None else '{%d, %d}' % s for s in row['sercom'])
            lines.append(f'    {{{number}, {extint}, {{{adc}}}, {{{timers}}}, {{{sercoms}}}}}, /* {pad} */')
        lines += ['    {PIN_NONE, 0, 0, {NO_ADC, NO_ADC}, {{0x3f, 0, 0}, {0x3f, 0, 0}, {0x3f, 0, 0}}, {{0x3f, 0}, {0x3f, 0}}},', '};']
        return lines

    def memories(self):
        lines = []
        for space in self.device.find('address-spaces/address-space'):
            name, start, size = space.get('name'), num(space.get('start')), num(space.get('size'))
            lines += [f'#define {name}_ADDR _UL_({start:#010x})', f'#define {name}_SIZE _UL_({size:#x})']
        return lines

    def device_header(self, modules):
        params = {p.get('name'): p.get('value') for p in self.device.find('parameters')}
        out = [f'#ifndef _{DEVICE}_', f'#define _{DEVICE}_', '',
               '#if !(defined(__ASSEMBLY__) || defined(__IAR_SYSTEMS_ASM__))',
               '#include <stdint.h>',
               '#ifndef __cplusplus',
               'typedef volatile const uint32_t RoReg; typedef volatile const uint16_t RoReg16; typedef volatile const uint8_t RoReg8;',
               '#else',
               'typedef volatile uint32_t RoReg; typedef volatile uint16_t RoReg16; typedef volatile uint8_t RoReg8;',
               '#endif',
               'typedef volatile uint32_t WoReg; typedef volatile uint16_t WoReg16; typedef volatile uint8_t WoReg8;',
               'typedef volatile uint32_t RwReg; typedef volatile uint16_t RwReg16; typedef volatile uint8_t RwReg8;',
               '#endif',
               '#if !defined(SKIP_INTEGER_LITERALS)',
               '#define _U_(x) x ## U', '#define _L_(x) x ## L', '#define _UL_(x) x ## UL',
               '#else', '#define _U_(x) x', '#define _L_(x) x', '#define _UL_(x) x', '#endif', '',
               '#if !(defined(__ASSEMBLY__) || defined(__IAR_SYSTEMS_ASM__))']
        out += self.interrupts()
        out += ['#endif', '']
        for key in ['__CM4_REV', '__MPU_PRESENT', '__NVIC_PRIO_BITS', '__FPU_PRESENT', '__VTOR_PRESENT', '__Vendor_SysTickConfig']:
            out.append(f'#define {key} {params[key]}')
        out += ['#ifdef __cplusplus', 'extern "C" {', '#endif'] + self.vectors() + ['#ifdef __cplusplus', '}', '#endif']
        out += ['#include "core_cm4.h"', '']
        out += [f'#include "component/{m.lower()}.h"' for m in modules]
        out += [''] + self.instances() + self.memories() + [''] + self.pins()
        out += ['', f'#endif /* _{DEVICE}_ */']
        return out


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('atdf', type=Path)
    parser.add_argument('out', type=Path)
    args = parser.parse_args()
    raw = args.atdf.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != ATDF_SHA256:
        raise SystemExit(f'ATDF SHA-256 {digest} is not the admitted input')
    gen = Generator(ET.fromstring(raw))
    notice = NOTICE.format(pack=PACK, atdf=ATDF, sha=digest)
    modules = [m for m in gen.modules if m not in SKIPPED_MODULES]
    (args.out / 'component').mkdir(parents=True, exist_ok=True)
    for module in modules:
        (args.out / 'component' / f'{module.lower()}.h').write_text(notice + '\n'.join(gen.component(module)) + '\n')
    (args.out / f'{DEVICE.lower()}.h').write_text(notice + '\n'.join(gen.device_header(modules)) + '\n')
    (args.out / f'{DEVICE.lower()}_pins.c').write_text(notice + '\n'.join(gen.pin_table()) + '\n')
    (args.out / f'{DEVICE.lower()}_vectors.c').write_text(notice + '\n'.join(gen.vector_table()) + '\n')
    interrupts = sorted({i.get('module-instance') or i.get('name') for i in gen.device.find('interrupts')})
    report = dict(schema=1, pack=PACK, pack_sha256=PACK_SHA256, atdf=ATDF, atdf_sha256=digest, device=DEVICE,
                  modules=modules, interrupts=interrupts,
                  outputs={p.relative_to(args.out).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
                           for p in sorted(args.out.rglob('*')) if p.is_file()})
    (args.out / 'generator.json').write_text(json.dumps(report, indent=2, sort_keys=True) + '\n')
    print(f'SAMD51_DEVICE_HEADERS atdf_sha256={digest} modules={len(modules)}')


if __name__ == '__main__':
    main()
